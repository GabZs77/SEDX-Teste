import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = readFileSync(new URL('./platforms-tab.js', import.meta.url), 'utf8');
const helpers = source.slice(source.indexOf('  const canReply ='), source.indexOf('  function renderReplyPreview'));
const rules = vm.runInNewContext(helpers + '\n({ canReply, replyExcerpt, splitReply, replyContent, horizontalReply })', { currentRa: () => '123' });
assert.equal(rules.canReply({authorRa:'456',content:'Olá'}), true);
assert.equal(rules.canReply({authorRa:'123',content:'Minha'}), false);
assert.equal(rules.canReply({authorRa:'456',deleted:true}), false);
assert.equal(rules.horizontalReply(70, 4), true);
assert.equal(rules.horizontalReply(-70, 4), true);
assert.equal(rules.horizontalReply(12, 90), false);
assert.equal(rules.horizontalReply(20, 1), false);
const encoded = rules.replyContent('Minha resposta', {name:'Aluno A.', excerpt:'Pergunta original'});
assert.equal(encoded, '> Aluno A.\n> Pergunta original\n\nMinha resposta');
assert.equal(rules.splitReply(encoded).content, 'Minha resposta');
assert.equal(rules.splitReply(encoded).excerpt, 'Pergunta original');
assert.equal(rules.replyExcerpt({content:encoded}), 'Minha resposta');
assert.equal(rules.replyExcerpt({audioUrl:'audio'}), 'Áudio');
console.log('OK: swipe direction, own/deleted messages, and persisted quoted reply');
